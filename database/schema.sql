create table if not exists public.equipment (
 id bigint generated by default as identity primary key,
 equipment_name text not null check(length(trim(equipment_name))>0),
 category text not null,
 asset_code text unique not null,
 condition text not null default 'Good' check(condition in ('Good','Fair','For Repair')),
 availability text not null default 'Available' check(availability in ('Available','Borrowed')),
 created_at timestamptz not null default now()
);
create table if not exists public.borrow_transactions (
 id bigint generated by default as identity primary key,
 equipment_id bigint not null references public.equipment(id) on delete restrict,
 borrower_name text not null check(length(trim(borrower_name))>0),
 borrower_type text not null check(borrower_type in ('Student','Faculty','Staff')),
 department text not null,
 date_borrowed date not null default current_date,
 due_date date not null,
 date_returned date,
 status text not null default 'Borrowed' check(status in ('Borrowed','Returned','Overdue')),
 user_id uuid not null references auth.users(id),
 created_at timestamptz not null default now(),
 constraint due_after_borrow check(due_date>=date_borrowed),
 constraint returned_date_required check(status<>'Returned' or date_returned is not null)
);
create index if not exists idx_borrow_equipment on public.borrow_transactions(equipment_id);
create index if not exists idx_borrow_due on public.borrow_transactions(due_date,status);
alter table public.equipment enable row level security;
alter table public.borrow_transactions enable row level security;
drop policy if exists "Authenticated equipment access" on public.equipment;
create policy "Authenticated equipment access" on public.equipment for all to authenticated using(true) with check(true);
drop policy if exists "Authenticated transaction access" on public.borrow_transactions;
create policy "Authenticated transaction access" on public.borrow_transactions for all to authenticated using(true) with check(user_id=auth.uid());
